func formatProbes() []string {
	var out []string

	seen := map[string]bool{"": true}
	add := func(s string) {
		if !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}

	for _, s := range []string{
		"plain", "100% sure", "%d%% done", "%[1]s or %[2]s", "%s and %d", "%[2]s %[1]s",
		"%-8.3f|%+v|%x", "%*d", "%[3]*.[2]*[1]f", "bad %z verb", "trailing %", "%5%", "50%% off",
		"%v", "%[2]d only", "% d", "%[0]d", "%!", "%p", "%w", "%%", "%", "x %d y", "%d and %z",
	} {
		add(s)
	}

	// Repeated argument: every ordered pair of verbs, '*' as a width.
	uses := strings.Split("b c d e E f F g G o O q s t T U v x X", " ")
	uses = append(uses, "*d")

	for _, a := range uses {
		for _, b := range uses {
			add("%[1]" + a + " %[1]" + b)
		}
	}

	for _, s := range []string{
		"%[+1]d", "%[01]d", "%[65536]d", "%[ 1]d", "%[1000000]d", "%[1000001]d", "%[2147483647]d",
		"%[2147483648]d", "%[4294967295]d", "%[-1]d", "%[1 ]d", "%[]d", "%[00000000000000000001]d",
		"%[99999999999999999999]d", "%5[1]d", "%.3[1]d",
		"%[1]d %[1]s", "%[1]d %[1]d", "%[1]s %[1]v", "%[2]d %[1]s %[2]s", "%d %[1]s", "%[1]x %[1]X",
		"%[1]d %[1]f", "%[1]c %[1]U", "%s %[1]d", "%[1]*d %[1]d", "%[1]d %[1]*d", "%[1]*d %[1]*d",
		"%[1]x %[1]s %[1]d", "%[1]x %[1]s %[1]q", "%[1]v %[1]s %[1]d", "%d %d %[1]s", "%s %[1]s %[1]v",
	} {
		add(s)
	}

	prefixes := []string{
		"%", "%5", "%-5.2", "%+", "%#", "%0", "% ", "%.", "%.3", "%[1]", "%[0]", "%[2]",
		"%*", "%.*", "%[1]*.[2]*[3]", "%[", "%[1", "%[x]",
	}
	for _, p := range prefixes {
		for c := 32; c < 127; c++ {
			add(p + string(rune(c)))
		}
	}

	return out
}

func flaggedByLine(raw []byte) map[int]bool {
	out := map[int]bool{}

	for _, chunk := range strings.Split(string(raw), "\n\n") {
		_, rest, ok := strings.Cut(chunk, "#: probe.go:")
		if !ok {
			continue
		}

		num, _, _ := strings.Cut(rest, "\n")
		num, _, _ = strings.Cut(num, " ")

		n, err := strconv.Atoi(num)
		if err != nil {
			continue
		}

		out[n] = strings.Contains(chunk, "#, go-format")
	}

	return out
}

func oracleVersion(tb testing.TB) string {
	tb.Helper()

	out, err := exec.Command("xgettext", "--version").Output()
	require.NoError(tb, err)

	first, _, _ := strings.Cut(string(out), "\n")

	return first
}

func TestUpdateCorpora(t *testing.T) {
	if !*update {
		t.Skip("run with -update to regenerate the corpora")
	}

	requireOracle(t)

	banner := "# generated by: go test ./internal/tools/i18nscan -run TestUpdateCorpora -update\n# " +
		oracleVersion(t) + "\n"

	probes := formatProbes()
	lines := make([]string, len(probes))

	for i, p := range probes {
		lines[i] = "Get(" + strconv.Quote(p) + ")"
	}

	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, "probe.go"), []byte(strings.Join(lines, "\n")+"\n"), 0o600))

	raw, err := runXgettext(dir, []string{"probe.go"})
	require.NoError(t, err)

	flagged := flaggedByLine(raw)

	var b strings.Builder

	b.WriteString(banner)

	for i, p := range probes {
		flag := "0"
		on, found := flagged[i+1]
		require.True(t, found, "probe %d missing from oracle output: %q", i+1, p)

		if on {
			flag = "1"
		}

		b.WriteString(strconv.Quote(p) + "\t" + flag + "\n")
	}

	require.NoError(t, os.WriteFile(formatCorpus, []byte(b.String()), 0o600))

	b.Reset()
	b.WriteString(banner)

	for _, pair := range pluralProbes {
		src := "GetN(" + strconv.Quote(pair[0]) + ", " + strconv.Quote(pair[1]) + ", 1)\n"
		d := t.TempDir()
		require.NoError(t, os.WriteFile(filepath.Join(d, "probe.go"), []byte(src), 0o600))

		verdict, flag := "ok", "0"

		out, err := runXgettext(d, []string{"probe.go"})
		if err != nil {
			verdict = "err"
		} else if strings.Contains(string(out), "#, go-format") {
			flag = "1"
		}

		b.WriteString(strconv.Quote(pair[0]) + "\t" + strconv.Quote(pair[1]) + "\t" + verdict + "\t" + flag + "\n")
	}

	require.NoError(t, os.WriteFile(pluralCorpus, []byte(b.String()), 0o600))
}

func TestFormatCorpus(t *testing.T) {
	rows := readTSV(t, formatCorpus)
	probes := formatProbes()
	require.Len(t, rows, len(probes), "corpus missing or stale; regenerate with -update")

	flagged := 0

	for i, r := range rows {
		require.Len(t, r, 2)
		require.Equal(t, strconv.Quote(probes[i]), r[0], "row %d is stale; regenerate with -update", i)

		s, err := strconv.Unquote(r[0])
		require.NoError(t, err)

		want := r[1] == "1"
		if want {
			flagged++
		}

		assert.Equal(t, want, isGoFormat(s), "%s", r[0])
	}

	assert.Greater(t, flagged, 50)
	assert.Less(t, flagged, len(rows)-50)
}

func TestPluralCorpus(t *testing.T) {
	rows := readTSV(t, pluralCorpus)
	require.Len(t, rows, len(pluralProbes), "corpus missing or stale; regenerate with -update")

	for i, r := range rows {
		require.Len(t, r, 4)
		require.Equal(t, strconv.Quote(pluralProbes[i][0]), r[0], "row %d is stale; regenerate with -update", i)
		require.Equal(t, strconv.Quote(pluralProbes[i][1]), r[1], "row %d is stale; regenerate with -update", i)

		id, err := strconv.Unquote(r[0])
		require.NoError(t, err)

		plural, err := strconv.Unquote(r[1])
		require.NoError(t, err)

		assert.Equal(t, r[2] == "ok", checkPlural(id, plural) == nil, "%s / %s", r[0], r[1])

		if r[2] == "ok" {
			assert.Equal(t, r[3] == "1", isGoFormatPair(id, plural), "flag %s / %s", r[0], r[1])
		}
	}
}
